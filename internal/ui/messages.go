package ui

import "fmt"

// T returns the message for key in lang (falling back to English).
func T(lang, key string, args ...any) string {
	cat, ok := messages[lang]
	if !ok {
		cat = messages["en"]
	}
	text, ok := cat[key]
	if !ok {
		text = messages["en"][key]
	}
	if text == "" {
		text = key
	}
	if len(args) > 0 {
		return fmt.Sprintf(text, args...)
	}
	return text
}

